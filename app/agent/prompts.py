def build_user_prompt(code: str, name: str | None, question: str | None) -> str:
    title = f"{clean_name(name)}（{code}）" if name else code
    focus = (question or "").strip() or "全面分析，重点看财务同比趋势、同业估值、业绩预告（如有）与最新公告新闻。"
    return (
        f"分析标的：{title}\n"
        f"股票代码：{code}\n"
        f"用户关注点：{focus}\n\n"
        "请作为主编排，调用一次子智能体 `research_pipeline` 完成六维分析：\n"
        "1) 基本面画像（财务同比/环比趋势为主；有业绩预告则必写）\n"
        "2) 股性判定 + 估值框架（不唯 PE/PB）\n"
        "3) 板块联动与同业对比（行业涨跌联动 + 成分股业绩/PE/PB/现金流横向对比 + 行业动态）\n"
        "4) 技术面辅助\n"
        "5) 公司最新公告/新闻 + 情报补缺\n"
        "6) 按固定大纲汇总完整报告\n\n"
        f"{REPORT_OUTLINE}\n"
        "不要调用 execute/shell。"
    )


def build_stage_user_message(
    *,
    code: str,
    name: str,
    question: str,
    stage_hint: str,
    prior_notes: str,
) -> str:
    title = f"{name}（{code}）" if name else code
    return (
        f"分析标的：{title}\n"
        f"股票代码：{code}\n"
        f"用户关注点：{question or '全面分析，财务趋势与最新动态优先'}\n\n"
        f"{stage_hint}\n\n"
        f"此前阶段产出：\n{prior_notes or '（无）'}\n"
    )


